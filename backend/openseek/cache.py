"""Tile cache (SR-15, SR-16).

Layout (every component derived from validated lowercase hex IDs / integers):
  <data>/cache/<fp[0:2]>/<fp>/<PROFILE>/tiles/<k>.jpg
  <data>/cache/<fp[0:2]>/<fp>/<PROFILE>/sheets/<n>_<v>.jpg
Tiles are written individually and atomically (temp + fsync + rename) and are immutable once
published. Every read validates the JPEG (SOI/EOI markers + recorded size); a corrupt tile is
deleted, unpublished and regenerated by the scheduler. Sheets (10x10 tiles, 3200x1800) are
composed on demand from tiles and cached per fill version. Eviction: least recently used
fingerprint first when the total exceeds the byte cap, plus age-based retention.
"""
from __future__ import annotations

import io
import logging
import os
import secrets
import shutil
import threading
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from .db import DB
from .ids import is_fingerprint

log = logging.getLogger("openseek.cache")

PROFILE = "t320x180q75g10v1"   # tile geometry/quality/grid/extractor version (part of the path)
TILE_W, TILE_H = 320, 180
SHEET_COLS = SHEET_ROWS = 10
PER_SHEET = SHEET_COLS * SHEET_ROWS
MIN_JPEG = 125
POSIX = os.name == "posix"


def jpeg_ok(data: bytes | None) -> bool:
    return bool(data) and len(data) >= MIN_JPEG and data[:3] == b"\xff\xd8\xff" and data[-2:] == b"\xff\xd9"


def secure_mkdir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    if POSIX:
        os.chmod(path, 0o700)


def atomic_write(path: Path, data: bytes) -> None:
    tmp = path.with_name(f".{path.name}.{secrets.token_hex(6)}.tmp")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    fd = os.open(tmp, flags, 0o600)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    if POSIX:
        try:
            dfd = os.open(path.parent, os.O_RDONLY)
            try:
                os.fsync(dfd)
            finally:
                os.close(dfd)
        except OSError:
            pass


@dataclass
class Entry:
    fp: str
    duration_ms: int | None = None
    n_tiles: int | None = None
    version: int = 0
    bytes: int = 0
    last_used: float = 0.0
    tiles: dict[int, int] = field(default_factory=dict)      # k -> pts_ms
    sizes: dict[int, int] = field(default_factory=dict)      # k -> file size
    sheet_files: dict[int, tuple[int, int]] = field(default_factory=dict)  # n -> (v, size)
    lock: threading.RLock = field(default_factory=threading.RLock)
    _flushed_use: float = 0.0


class Cache:
    def __init__(self, data_dir: Path, db: DB, max_bytes: int, retention_days: float,
                 clock: Callable[[], float] = time.time):
        self.root = Path(data_dir) / "cache"
        secure_mkdir(self.root)
        self.db = db
        self.max_bytes = max_bytes
        self.retention_s = retention_days * 86400.0
        self.clock = clock
        self._entries: dict[str, Entry] = {}
        self._lock = threading.RLock()
        self.on_tile_lost: Callable[[str, int], None] | None = None
        self._cleanup_tmp()

    # ---------------------------------------------------------------- paths
    def _dir(self, fp: str) -> Path:
        if not is_fingerprint(fp):
            raise ValueError("invalid fingerprint")
        return self.root / fp[:2] / fp / PROFILE

    def _tile_path(self, fp: str, k: int) -> Path:
        if not isinstance(k, int) or k < 0 or k > 10_000_000:
            raise ValueError("invalid tile index")
        return self._dir(fp) / "tiles" / f"{k}.jpg"

    def _sheet_path(self, fp: str, n: int, v: int) -> Path:
        if not isinstance(n, int) or n < 0 or not isinstance(v, int) or v < 0:
            raise ValueError("invalid sheet")
        return self._dir(fp) / "sheets" / f"{n}_{v}.jpg"

    def _cleanup_tmp(self) -> None:
        for p in self.root.glob("*/*/*/*/.*.tmp"):
            try:
                p.unlink()
            except OSError:
                pass

    # ---------------------------------------------------------------- entries
    def entry(self, fp: str) -> Entry | None:
        if not is_fingerprint(fp):
            return None
        with self._lock:
            e = self._entries.get(fp)
            if e is not None:
                return e
            rows = self.db.q("SELECT duration_ms, n_tiles, version, bytes, last_used FROM entries WHERE fp=?",
                             (fp,))
            if not rows:
                return None
            d, n, v, b, lu = rows[0]
            e = Entry(fp, d, n, v, b, lu)
            e._flushed_use = lu
            for k, pts, size in self.db.q("SELECT k, pts_ms, size FROM tiles WHERE fp=?", (fp,)):
                e.tiles[k] = pts
                e.sizes[k] = size
            # sheets are derived data: drop leftovers from a previous run and recount bytes
            shutil.rmtree(self._dir(fp) / "sheets", ignore_errors=True)
            e.bytes = sum(e.sizes.values())
            self.db.x("UPDATE entries SET bytes=? WHERE fp=?", (e.bytes, fp))
            self._entries[fp] = e
            return e

    def ensure(self, fp: str) -> Entry:
        if not is_fingerprint(fp):
            raise ValueError("invalid fingerprint")
        with self._lock:
            e = self.entry(fp)
            if e is None:
                now = self.clock()
                self.db.x("INSERT OR IGNORE INTO entries(fp, version, bytes, created, last_used) VALUES(?,?,?,?,?)",
                          (fp, 0, 0, now, now))
                e = self.entry(fp)
            assert e is not None
            return e

    def set_media(self, fp: str, duration_ms: int, n_tiles: int) -> None:
        e = self.ensure(fp)
        with e.lock:
            e.duration_ms, e.n_tiles = duration_ms, n_tiles
            self.db.x("UPDATE entries SET duration_ms=?, n_tiles=? WHERE fp=?", (duration_ms, n_tiles, fp))

    def touch(self, fp: str) -> None:
        e = self.entry(fp)
        if e is None:
            return
        now = self.clock()
        e.last_used = now
        if now - e._flushed_use > 60:
            e._flushed_use = now
            self.db.x("UPDATE entries SET last_used=? WHERE fp=?", (now, fp))

    # ---------------------------------------------------------------- tiles
    def put_tile(self, fp: str, k: int, pts_ms: int, data: bytes) -> int:
        """Publish tile k (immutable). Returns the entry's new version."""
        if not jpeg_ok(data):
            raise ValueError("not a JPEG")
        e = self.ensure(fp)
        with e.lock:
            if k in e.tiles:
                return e.version
            path = self._tile_path(fp, k)
            secure_mkdir(path.parent)
            atomic_write(path, data)
            e.tiles[k] = int(pts_ms)
            e.sizes[k] = len(data)
            e.version += 1
            e.bytes += len(data)
            now = self.clock()
            e.last_used = now
            self.db.tx([
                ("INSERT OR REPLACE INTO tiles(fp,k,pts_ms,size,created) VALUES(?,?,?,?,?)",
                 (fp, k, int(pts_ms), len(data), now)),
                ("UPDATE entries SET version=?, bytes=?, last_used=? WHERE fp=?", (e.version, e.bytes, now, fp)),
            ])
            return e.version

    def drop_tile(self, fp: str, k: int) -> None:
        e = self.entry(fp)
        if e is None:
            return
        with e.lock:
            if k not in e.tiles:
                return
            try:
                self._tile_path(fp, k).unlink()
            except OSError:
                pass
            e.tiles.pop(k, None)
            e.bytes -= e.sizes.pop(k, 0)
            e.version += 1
            self.db.tx([("DELETE FROM tiles WHERE fp=? AND k=?", (fp, k)),
                        ("UPDATE entries SET version=?, bytes=? WHERE fp=?", (e.version, e.bytes, fp))])
        log.warning("tile %d of %s.. was corrupt; dropped for regeneration", k, fp[:8])
        cb = self.on_tile_lost
        if cb:
            cb(fp, k)

    def drop_tiles_quiet(self, fp: str, ks) -> int:
        """Remove many tiles in ONE transaction without the per-tile regeneration callback (the caller marks
        them missing and wakes the runner once). Returns how many were removed."""
        e = self.entry(fp)
        if e is None:
            return 0
        removed = []
        with e.lock:
            for k in ks:
                if k not in e.tiles:
                    continue
                try:
                    self._tile_path(fp, k).unlink()
                except OSError:
                    pass
                e.tiles.pop(k, None)
                e.bytes -= e.sizes.pop(k, 0)
                removed.append(k)
            if removed:
                e.version += 1
                self.db.tx([("DELETE FROM tiles WHERE fp=? AND k=?", (fp, k)) for k in removed]
                           + [("UPDATE entries SET version=?, bytes=? WHERE fp=?", (e.version, e.bytes, fp))])
        return len(removed)

    def tile_bytes(self, fp: str, k: int) -> bytes | None:
        e = self.entry(fp)
        if e is None or k not in e.tiles:
            return None
        try:
            data = self._tile_path(fp, k).read_bytes()
        except (OSError, ValueError):
            data = None
        if not jpeg_ok(data) or len(data) != e.sizes.get(k, -1):
            self.drop_tile(fp, k)
            return None
        return data

    # ---------------------------------------------------------------- sheets
    def sheet_fill(self, e: Entry, n: int) -> int:
        return sum(1 for k in e.tiles if k // PER_SHEET == n)

    def sheet_bytes(self, fp: str, n: int) -> tuple[bytes, int] | None:
        """Compose (or reuse) sheet n with the tiles published now. Unfilled slots are black."""
        e = self.entry(fp)
        if e is None or n < 0:
            return None
        with e.lock:
            ks = sorted(k for k in e.tiles if k // PER_SHEET == n)
            if not ks:
                return None
            v = len(ks)
            path = self._sheet_path(fp, n, v)
            cached = e.sheet_files.get(n)
            if cached and cached[0] == v:
                try:
                    data = path.read_bytes()
                    if jpeg_ok(data) and len(data) == cached[1]:
                        return data, v
                except OSError:
                    pass
            from PIL import Image

            sheet = Image.new("RGB", (TILE_W * SHEET_COLS, TILE_H * SHEET_ROWS))
            for k in ks:
                tile = self.tile_bytes(fp, k)
                if tile is None:
                    continue           # corrupt tile was dropped; leave the slot black
                with Image.open(io.BytesIO(tile)) as im:
                    slot = k % PER_SHEET
                    sheet.paste(im.convert("RGB"), ((slot % SHEET_COLS) * TILE_W, (slot // SHEET_COLS) * TILE_H))
            ks2 = [k for k in ks if k in e.tiles]
            v = len(ks2)
            if v == 0:
                return None
            buf = io.BytesIO()
            sheet.save(buf, "JPEG", quality=75)
            data = buf.getvalue()
            path = self._sheet_path(fp, n, v)
            secure_mkdir(path.parent)
            atomic_write(path, data)
            old = e.sheet_files.get(n)
            if old and old[0] != v:
                try:
                    self._sheet_path(fp, n, old[0]).unlink()
                except OSError:
                    pass
            e.bytes += len(data) - (old[1] if old else 0)
            e.sheet_files[n] = (v, len(data))
            self.db.x("UPDATE entries SET bytes=? WHERE fp=?", (e.bytes, fp))
            return data, v

    # ---------------------------------------------------------------- eviction
    def total_bytes(self) -> int:
        r = self.db.q("SELECT COALESCE(SUM(bytes),0) FROM entries")
        return int(r[0][0])

    def stats(self) -> dict:
        r = self.db.q("SELECT COUNT(*), COALESCE(SUM(bytes),0) FROM entries")
        t = self.db.q("SELECT COUNT(*) FROM tiles")
        return {"entries": r[0][0], "bytes": r[0][1], "tiles": t[0][0], "max_bytes": self.max_bytes}

    def _delete_entry(self, fp: str) -> None:
        with self._lock:
            e = self._entries.pop(fp, None)
            lock = e.lock if e else threading.RLock()
            with lock:
                shutil.rmtree(self.root / fp[:2] / fp, ignore_errors=True)
                self.db.tx([("DELETE FROM tiles WHERE fp=?", (fp,)), ("DELETE FROM entries WHERE fp=?", (fp,)),
                            ("DELETE FROM previews WHERE fp=?", (fp,)), ("DELETE FROM release_meta WHERE fp=?", (fp,)),
                            ("DELETE FROM borrowed WHERE src_fp=?", (fp,)), ("DELETE FROM offsets WHERE src_fp=?", (fp,))])

    def remove_entry(self, fp: str) -> bool:
        """Owner action (admin API): delete ONE cache entry. False when it is unknown."""
        if not is_fingerprint(fp) or not self.db.q("SELECT 1 FROM entries WHERE fp=?", (fp,)):
            return False
        self._delete_entry(fp)
        return True

    def evict(self, protected: set[str] | frozenset[str] = frozenset()) -> list[str]:
        with self._lock:
            for fp, e in self._entries.items():   # flush in-memory last-use times
                if e.last_used > e._flushed_use:
                    e._flushed_use = e.last_used
                    self.db.x("UPDATE entries SET last_used=? WHERE fp=?", (e.last_used, fp))
            rows = self.db.q("SELECT fp, bytes, last_used FROM entries ORDER BY last_used ASC")
            total = sum(r[1] for r in rows)
            now = self.clock()
            gone = []
            for fp, size, last in rows:
                if fp in protected or not is_fingerprint(fp):
                    continue
                if now - last > self.retention_s or total > self.max_bytes:
                    self._delete_entry(fp)
                    total -= size
                    gone.append(fp)
            if gone:
                log.info("evicted %d cache entries; total now %d bytes", len(gone), total)
            return gone
