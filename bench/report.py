"""Render results/results.json into results/REPORT.md.

Hand-written analysis lives in bench/report_notes.txt and is placed at the top verbatim;
everything below it is generated from measured data only.
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent


def mb(x):
    return "-" if x is None else f"{x / 1e6:.2f}"


def f2(x, nd=2):
    if x is None:
        return "-"
    if isinstance(x, (int, float)):
        return f"{x:.{nd}f}"
    return str(x)


def acc(a):
    if not a or not a.get("n"):
        return "-"
    return f"{a['min_err_s']:+.2f}..{a['max_err_s']:+.2f}"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def ranges(log, n=8):
    if not log:
        return "-"
    return "<br>".join(f"`{l['range']}`→{l['status']} {l['bytes'] / 1e3:.0f}kB" for l in log[:n])


def strat_row(r):
    """Uniform row for ffmpeg per-process, S3 and S5 records."""
    if r["strategy"].startswith("S5"):
        return [r["strategy"], r.get("n", "-"), f"{r['ok']}/{r['n']}", f2(r.get("cold_first_s")),
                f2(r.get("warm_frame_s_mean")), f2(r.get("warm_frame_s_p95")), mb(r.get("bytes_per_frame")),
                f2(r.get("requests_per_frame")), f2(r.get("cpu_s_per_frame"), 3),
                f2((r.get("peak_rss") or 0) / 1e6, 0), acc(r.get("accuracy")), r.get("error") or ""]
    if r["strategy"].startswith("S3"):
        return [r["strategy"], r.get("n"), f"{r['ok']}/{r['n']}", f"(total {f2(r.get('total_wall_s'))})",
                f2(r.get("frame_s_mean")), "-", mb(r.get("bytes_per_frame")), f2(r.get("requests_per_frame")),
                f2(r.get("cpu_s_per_frame"), 3), f2((r.get("peak_rss_max") or 0) / 1e6, 0),
                acc(r.get("accuracy")), r.get("error") or ""]
    return [r["strategy"], r.get("n"), f"{r['ok']}/{r['n']}", f2(r.get("cold_first_s")), f2(r.get("frame_s_mean")),
            f2(r.get("frame_s_p95")), mb(r.get("bytes_per_frame")), f2(r.get("requests_per_frame")),
            f2(r.get("cpu_s_per_frame"), 3), f2((r.get("peak_rss_max") or 0) / 1e6, 0), acc(r.get("accuracy")),
            ",".join(r.get("errors") or [])]


STRAT_H = ["strategy", "frames", "ok", "cold first (s)", "per-frame mean (s)", "p95 (s)", "MB/frame",
           "req/frame", "CPU-s/frame", "peak RSS MB", "ts error (s)", "errors"]


def write(R: dict, path: Path):
    md = ["# OpenSeek Gate 1 — remote thumbnail extraction benchmark\n"]
    notes = HERE / "report_notes.txt"
    if notes.exists():
        md.append(notes.read_text(encoding="utf-8"))
        md.append("\n---\n\n# Measured data (generated by run_bench.py — do not edit by hand)\n")
    env = R.get("env")
    if env:
        md.append("## Environment\n")
        md.append(table(["key", "value"], [[k, v] for k, v in env.items() if k not in ("fixtures", "profiles")]))
        md.append("\nNetwork profiles (applied by server.py): " + ", ".join(
            f"`{k}` = {v or 'unthrottled localhost'}" for k, v in env["profiles"].items()) + "\n")
        md.append("\n**Fixtures** (synthetic, testsrc2 + temporal noise + frame-number barcode):\n\n")
        md.append(table(["file", "GB", "duration s", "Mbit/s"],
                        [[k, f"{v['bytes'] / 1e9:.3f}", f"{v['duration']:.0f}", f"{v['bit_rate'] / 1e6:.1f}"]
                         for k, v in env["fixtures"].items()]))
    if R.get("timings"):
        md.append("\nExperiment wall times (s): " + ", ".join(f"{k} {v}" for k, v in R["timings"].items()) + "\n")

    if R.get("containers"):
        md.append("\n## 1. Container / index layout (cold single frame, `cdn` profile)\n")
        md.append("One cold frame per run (fresh process / fresh container). Request log = every HTTP request "
                  "the server saw, with bytes actually sent.\n\n")
        rows = []
        for r in R["containers"]:
            if r["strategy"].startswith("S5"):
                rows.append([r["fixture"], r["strategy"], f"{r['ok']}/{r['n']}", f2(r.get("cold_first_s")),
                             mb(r.get("server_bytes")), r.get("server_requests"), r.get("server_connections"),
                             ranges(r.get("request_log"), 4) + (" …" if (r.get("server_requests") or 0) > 4 else "")])
            else:
                rows.append([r["fixture"], r["strategy"], f"{r['ok']}/{r['n']}", f2(r.get("cold_first_s")),
                             mb(r.get("bytes_total")), r.get("server_requests"), r.get("server_connections"),
                             ranges(r.get("request_log"), 6) + (" …" if (r.get("server_requests") or 0) > 6 else "")])
        md.append(table(["fixture", "strategy", "ok", "time (s)", "MB", "requests", "TCP conns", "requests (range → status, bytes)"], rows))

    if R.get("strategies"):
        md.append("\n## 2. Strategy comparison on `remux_like.mkv` (17.6 GB, 82 min, 28.7 Mbit/s, GOP 2 s)\n")
        md.append("Run in the order 1 → 5 → 20 frames. Per-process strategies: cold = the first process; "
                  "per-frame mean includes that process. S5: cold = process start → first JPEG written (includes "
                  "Python start, open, header/Cues); per-frame = warm grabs after the first. ts error = "
                  "extracted frame time minus requested time (decoded from the burned-in barcode).\n")
        for prof in ("cdn", "lan"):
            for n in (1, 5, 20):
                rows = [strat_row(r) for r in R["strategies"] if r.get("profile") == prof and r.get("n_frames") == n]
                if rows:
                    md.append(f"\n### profile `{prof}`, {n} frame(s)\n\n")
                    md.append(table(STRAT_H, rows))
    if R.get("strategies_localfile"):
        md.append("\n### Local file (no network) — CPU floor of the same commands, 5 frames\n\n")
        md.append(table(STRAT_H, [strat_row(r) for r in R["strategies_localfile"]]))
    if R.get("s5_libavio"):
        r = R["s5_libavio"]
        md.append(f"\n### PyAV using libav's built-in HTTP IO (not our RangeReader), small.mkv 60 MB, 3 frames\n\n"
                  f"bytes sent by server = {mb(r.get('server_bytes'))} MB for a {mb(r.get('file_bytes'))} MB file; "
                  f"cold first = {f2(r.get('cold_first_s'))} s; per-frame walls = "
                  f"{[f['wall_s'] for f in r['frames']]}; ts check = {acc(r.get('accuracy'))}.\n")
    if R.get("gop10"):
        md.append("\n## 3. Long GOP (10 s keyframe interval), `gop10.mkv`, `cdn`, 5 frames\n\n")
        md.append(table(STRAT_H, [strat_row(r) for r in R["gop10"]]))
    if R.get("hdr"):
        md.append("\n## 4. 4K HEVC Main10 HDR10 (PQ) → SDR thumbnails, `hdr4k.mkv`, `cdn`, 5 frames\n\n")
        md.append("hdr mode: `small` = downscale then zscale+tonemap(hable) at 320x180; `full` = tonemap at 3840x2160 "
                  "then downscale; `placebo` = libplacebo (Vulkan, GPU); `none` = no tonemap (washed-out output, "
                  "cost reference); S5 = numpy Hable at thumbnail size.\n\n")
        rows = []
        for r in R["hdr"]:
            row = strat_row(r)
            row[0] = f"{row[0]} [{r.get('hdr_mode')}]"
            rows.append(row)
        md.append(table(STRAT_H, rows))
    if R.get("sequential"):
        md.append("\n## 5. S4 naive sequential decode (fps=1/10), `med_cues_end.mkv` (0.86 GB, 240 s)\n\n")
        md.append(table(["profile", "thumbs", "wall s", "media-s per wall-s", "CPU s", "peak RSS MB", "MB sent",
                         "fraction of file", "requests", "ts error"],
                        [[r["profile"], r["frames"], r["wall_s"], r["media_s_per_wall_s"], f2(r["cpu_s"]),
                          f2((r["peak_rss"] or 0) / 1e6, 0), mb(r["bytes"]), r["bytes_fraction_of_file"],
                          r["requests"], acc(r["accuracy"])] for r in R["sequential"]]))
    F = R.get("failures")
    if F:
        md.append("\n## 6. Failure modes\n")
        nr = F.get("no_range", [])
        if nr:
            pf = nr[0]
            md.append(f"\n### Server without Range support\n\npreflight on a Range server: `{pf['range_server']}`  \n"
                      f"preflight on a no-Range server: `{pf['norange_server']}` "
                      f"(server sent {mb(pf['norange_preflight_bytes'])} MB before the client hung up)\n\n")
            rows = []
            for r in nr[1:]:
                if r["strategy"].startswith("S5"):
                    rows.append([r["fixture"], r["strategy"], f"{r['ok']}/{r['n']}", f2(r.get("process_wall_s")),
                                 mb(r.get("server_bytes")), r.get("error")])
                else:
                    rows.append([r["fixture"], r["strategy"], f"{r['ok']}/{r['n']}", f2(r.get("cold_first_s")),
                                 f"{mb(r.get('bytes_total'))} ({r['bytes_total'] / r['file_bytes']:.0%} of file)",
                                 ",".join(r.get("errors") or []) + f" ts {acc(r.get('accuracy'))}"])
            md.append(table(["fixture", "strategy", "ok", "time (s)", "MB sent", "error / ts error"], rows))
        if F.get("redirect"):
            md.append("\n### 302 signed-redirect hop (`/r/<file>` → `/f/<file>?sig=…`), 5 frames\n\n")
            rows = []
            for r in F["redirect"]:
                rows.append([r["strategy"], f"{r['ok']}/{r['n']}", r.get("redirects_302"),
                             f2(r.get("frame_s_mean") or r.get("warm_frame_s_mean")),
                             f"`{r.get('logged_paths_sample', '')}`"])
            md.append(table(["strategy", "ok", "302s served", "per-frame s", "server log paths (redacted)"], rows))
        if F.get("expired"):
            md.append("\n### Expired link (403)\n\n")
            rows = []
            for r in F["expired"]:
                errs = [fr.get("error") for fr in r["frames"]]
                walls = [fr.get("wall_s") for fr in r["frames"]]
                rows.append([r["strategy"], r["server_cfg"].get("expire_after_requests") or
                             f"{r['server_cfg'].get('expire_after_s')} s", f"{r['ok']}/{r['n']}", errs, walls])
            md.append(table(["strategy", "expires after", "ok", "per-frame error", "per-frame s"], rows))
        if F.get("dropped"):
            md.append("\n### Connection dropped mid-body (after 200 kB)\n\n")
            rows = []
            for r in F["dropped"]:
                rows.append([r["strategy"], r["server_cfg"].get("drops"), f"{r['ok']}/{r['n']}",
                             f2(r.get("cold_first_s")), r.get("server_requests"),
                             (",".join(r.get("errors") or []) if "errors" in r else (r.get("error") or "")),
                             acc(r.get("accuracy"))])
            md.append(table(["strategy", "responses dropped (-1 = all)", "ok", "first s", "requests", "errors",
                             "ts error"], rows))
        if F.get("bad_input"):
            md.append("\n### Bad input, timeouts, cancellation\n\n")
            md.append(table(["case", "ok", "error", "wall s", "killed", "orphan process"],
                            [[r["case"], r["ok"], r["error"], r["wall_s"], r.get("killed", "-"), r.get("orphan", "-")]
                             for r in F["bad_input"]]))
    if R.get("concurrency"):
        md.append("\n## 7. Concurrency (16 frames over `remux_like.mkv`, `cdn`, shared 100 Mbit/s)\n\n")
        md.append(table(["strategy", "parallel", "wall s", "frames/s", "latency mean s", "latency p95 s",
                         "CPU-s/frame", "MB/frame"],
                        [[r["strategy"], r["parallel"], r["wall_s"], r["frames_per_s"], r["latency_mean_s"],
                          r["latency_p95_s"], r["cpu_s_per_frame"], mb(r["bytes_per_frame"])]
                         for r in R["concurrency"]]))
    if R.get("playback"):
        md.append("\n## 8. Playback-alongside proxy (player + thumbnailer share the 100 Mbit/s `cdn` link)\n\n")
        md.append("The player starts from a fresh seek (empty buffer) 0.3 s before the thumbnail job starts, needs "
                  "2.5 s of media to start, buffers up to 30 s ahead. `playback_ok` = no stall and start < 3 s.\n\n")
        md.append(table(["playback Mbit/s", "thumbnail job (16 frames)", "job window s", "startup s", "stalls",
                         "stall s", "player Mbit/s during job", "thumb MB", "ok"],
                        [[r["playback_mbps"], r["job"], r["job_window_s"], r["startup_s"], r["stalls"], r["stall_s"],
                          r["playback_mbps_during_job"], mb(r["thumb_bytes"]), r["playback_ok"]]
                         for r in R["playback"]]))
    if R.get("scrub"):
        md.append("\n## 9. ON-DEMAND: scrub to 80:00 on `remux_like.mkv`, `cdn` — cold / warm-source / warm-cache\n\n")
        md.append("Order: T=80:00 first, then 10 neighbours (79:10…80:50 every 10 s), then (S5 only) a far jump to "
                  "10:00 on the open source. **cold** = new job, nothing probed/opened (S5: process start → first "
                  "JPEG, includes open/header/Cues; S2/S1: preflight + ffprobe + first ffmpeg). **warm-source** = "
                  "source already probed/open, new timestamp (S5: persistent container; S2/S1: cached probe, but "
                  "each process re-reads header+Cues). **warm-cache** = generated JPEG served from disk over HTTP "
                  "through the same cdn profile (keep-alive; first request pays new-connection RTTs).\n\n")
        md.append(table(["strategy", "parallel", "cold first thumb s", "cold MB", "cold req", "warm-source s/frame (p95)",
                         "warm-source MB/frame", "warm-source req/frame", "all 11 done s", "far jump s",
                         "warm-cache s (first / reused conn)", "total MB", "total req", "ts error"],
                        [[r["strategy"], r["parallel"], r.get("cold_first_s"), mb(r.get("cold_bytes")),
                          r.get("cold_requests"), f"{f2(r.get('warm_source_mean_s'), 3)} ({f2(r.get('warm_source_p95_s'), 3)})",
                          mb(r.get("warm_source_bytes_per_frame")), r.get("warm_source_requests_per_frame"),
                          r.get("all_11_s"), r.get("far_jump_s", "-"),
                          f"{(r.get('warm_cache') or {}).get('first_s')} / {(r.get('warm_cache') or {}).get('mean_s_excl_first')}",
                          mb(r.get("total_bytes")), r.get("total_requests"), acc(r.get("accuracy"))]
                         for r in R["scrub"]]))
    if R.get("scrub_seq"):
        r = R["scrub_seq"]
        md.append(f"\n**Naive sequential (S4) from 0 to reach 80:00 ({r['target_t']} s):** "
                  f"time = {r.get('time_to_target_s')} s, bytes = {mb(r.get('bytes_at_target'))} MB, "
                  f"check = {r.get('check')}.\n")
    I = R.get("internet")
    if I:
        md.append("\n## 10. Real public remote files over the internet\n\n")
        md.append("ffmpeg runs go through the server's accounting proxy (`/u/…`, counts bytes forwarded to ffmpeg; "
                  "true wire bytes can exceed this by the proxy's socket buffers). S5 connects directly and counts "
                  "body bytes itself. Timestamp accuracy cannot be verified on real content (no barcode).\n")
        for name, rec in I.items():
            md.append(f"\n### {name}\n\nsource `{rec['source']}`  \npreflight `{rec.get('preflight')}`  \n"
                      f"probe `{rec.get('probe')}`  \n"
                      f"accounted bytes {mb(rec.get('bytes_used_accounted'))} MB; host NIC bytes received during "
                      f"the suite {mb(rec.get('net_io_recv_delta'))} MB (whole machine)\n\n")
            if rec.get("blocked"):
                md.append(f"BLOCKED: {rec['blocked']}\n")
            md.append(table(STRAT_H, [strat_row(r) for r in rec.get("runs", [])]))
    T = R.get("torbox")
    if T is not None:
        md.append("\n## 11. TorBox REMUX\n\n")
        if T.get("blocked"):
            md.append(f"**BLOCKED** — {T['blocked']}. {T.get('how', '')}\n")
        else:
            md.append(f"source `{T['source']}` preflight `{T.get('preflight')}` probe `{T.get('probe')}`\n\n")
            md.append(table(STRAT_H, [strat_row(r) for r in T.get("runs", [])]))
    md.append("\n## Reproduce\n\n```\ncd bench\npython -m pip install -r requirements.txt\npython fixtures.py\n"
              "python -m pytest -q tests\npython run_bench.py --quick    # ~5 min core subset -> results/quick/\n"
              "python run_bench.py            # full synthetic matrix (~1.5 h incl. ~30 min scrub_seq)\n"
              "python run_bench.py --exp internet\n"
              "OPENSEEK_BENCH_URL='<torbox link>' python run_bench.py --exp torbox --url-env OPENSEEK_BENCH_URL\n```\n")
    path.write_text("\n".join(md), encoding="utf-8")
